test("syncProblem: never synced, team.yaml edited since, a sync cut short; none after a sync", () => {
  const { lib, root, home } = setup(["core"]);
  assert.match(syncProblem(root) ?? "", /not synced yet: run otterpack sync/);
  sync(root, { home });
  assert.equal(syncProblem(root), undefined);
  writeFileSync(join(root, ".otterpack/team.yaml"), team(lib, ["core", "seo"]));
  assert.match(syncProblem(root) ?? "", /team\.yaml changed since the last sync: run otterpack sync/);
  sync(root, { home });
  assert.equal(syncProblem(root), undefined);
  const lock = JSON.parse(read(root, ".otterpack/lock.json"));
  writeFileSync(join(root, ".otterpack/lock.json"), JSON.stringify({ ...lock, pending: {} }));
  assert.match(syncProblem(root) ?? "", /last sync did not finish: run otterpack sync/);
  const { team: _t, ...older } = lock;
  writeFileSync(join(root, ".otterpack/lock.json"), JSON.stringify(older));
  assert.match(syncProblem(root) ?? "", /synced by an older otterpack: run otterpack sync/);
});

test("a comment or whitespace edit to team.yaml needs no sync", () => {
  const { lib, root, home } = setup(["core"]);
  sync(root, { home });
  writeFileSync(join(root, ".otterpack/team.yaml"), "# a comment\n" + team(lib, ["core"]).replace(/\n/g, "\r\n"));
  assert.equal(syncProblem(root), undefined);
});

test("an unreadable lock.json (a merge conflict) is a clear error, not a crash", () => {
  const { root, home } = setup(["core"]);
  sync(root, { home });
  writeFileSync(join(root, ".otterpack/lock.json"), "<<<<<<< HEAD\n{}\n");
  assert.throws(() => syncProblem(root), (e: Error) => e instanceof SyncError && /lock\.json is not valid JSON/.test(e.message));
});

/** The one backup folder a --replace sync made. */
function backup(root: string): string {
  const dirs = readdirSync(join(root, ".otterpack/replaced"));
  assert.equal(dirs.length, 1);
  return `.otterpack/replaced/${dirs[0]}`;
}

test("--replace moves hand-made files out of the way, keeps them in a backup, and syncs", () => {
  const { root, home } = setup(undefined, "", {
    ".claude/agents/planner.md": "hand-made planner\n",
    ".claude/skills/handoff/SKILL.md": "hand-made skill\n",
    ".claude/skills/handoff/notes.md": "my notes\n",
  });
  const r = sync(root, { home, replace: true });
  assert.equal(read(root, ".claude/agents/planner.md"), "---\nname: planner\n---\nplan\n");
  assert.equal(read(root, ".claude/skills/handoff/SKILL.md"), LIB["kits/core/skills/handoff/SKILL.md"]);
  const b = backup(root);
  assert.equal(r.backup, b);
  assert.equal(read(root, `${b}/.claude/agents/planner.md`), "hand-made planner\n");
  // a hand-made skill moves as a whole, so no stray file mixes into the generated one
  assert.equal(read(root, `${b}/.claude/skills/handoff/SKILL.md`), "hand-made skill\n");
  assert.equal(read(root, `${b}/.claude/skills/handoff/notes.md`), "my notes\n");
  assert.ok(!exists(root, ".claude/skills/handoff/notes.md"));
  assert.deepEqual(r.replaced.sort(), [".claude/agents/planner.md", ".claude/skills/handoff"]);
  assert.match(read(root, ".otterpack/.gitignore"), /^replaced\/$/m);
});

test("--replace also moves a generated file edited by hand", () => {
  const { root, home } = setup();
  sync(root, { home });
  writeFileSync(join(root, ".claude/agents/planner.md"), "edited\n");
  writeFileSync(join(root, ".otterpack/team.yaml"), read(root, ".otterpack/team.yaml").replace("label: PO", "label: Owner"));
  const r = sync(root, { home, replace: true });
  assert.deepEqual(r.replaced, [".claude/agents/planner.md"]);
  assert.equal(read(root, `${backup(root)}/.claude/agents/planner.md`), "edited\n");
  assert.equal(read(root, ".claude/agents/planner.md"), "---\nname: planner\n---\nplan\n");
});

test("--replace still stops on a symlink, and moves nothing", () => {
  const { root, home } = setup(["core"], "", { ".claude/agents/planner.md": "hand-made\n" });
  mkdirSync(join(root, ".agents/skills/handoff"), { recursive: true });
  mkdirSync(join(root, ".claude/skills"), { recursive: true });
  symlinkSync("../../.agents/skills/handoff", join(root, ".claude/skills/handoff"));
  assert.throws(() => sync(root, { home, replace: true }), /goes through the symlink/);
  assert.equal(read(root, ".claude/agents/planner.md"), "hand-made\n");
  assert.ok(!exists(root, ".otterpack/replaced"));
});

test("--replace with nothing in the way makes no backup, and lists the hand-made agents and skills it leaves", () => {
  const { root, home } = setup(["core"], "", { ".claude/agents/my-own.md": "mine\n", ".agents/skills/legacy/SKILL.md": "old\n" });
  const r = sync(root, { home, replace: true });
  assert.equal(r.backup, undefined);
  assert.ok(!exists(root, ".otterpack/replaced"));
  assert.deepEqual(r.unmanaged, [".agents/skills/legacy", ".claude/agents/my-own.md"]);
  assert.equal(read(root, ".claude/agents/my-own.md"), "mine\n");
});

test("--prune also moves the hand-made agents and skills no kit replaces (into the same backup)", () => {
  const { root, home } = setup(["core"], "", {
    ".claude/agents/planner.md": "hand-made planner\n",
    ".claude/agents/my-own.md": "mine\n",
    ".agents/skills/legacy/SKILL.md": "old\n",
  });
  const r = sync(root, { home, replace: true, prune: true });
  const b = backup(root);
  assert.deepEqual(r.replaced.sort(), [".agents/skills/legacy", ".claude/agents/my-own.md", ".claude/agents/planner.md"]);
  assert.equal(read(root, `${b}/.claude/agents/my-own.md`), "mine\n");
  assert.equal(read(root, `${b}/.agents/skills/legacy/SKILL.md`), "old\n");
  assert.deepEqual(r.unmanaged, []);
  assert.deepEqual(readdirSync(join(root, ".claude/agents")), ["planner.md"]);
});

test("--prune alone (no --replace) still stops on a conflict", () => {
  const { root, home } = setup(["core"], "", { ".claude/agents/planner.md": "hand-made\n" });
  assert.throws(() => sync(root, { home, prune: true }), /exists and was not generated/);
});

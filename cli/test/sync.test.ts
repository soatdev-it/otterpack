test("a sync that fails half-way can be run again once the cause is fixed", () => {
  const { root, home } = setup(["core"], "", { ".otterpack/local/personas/product-owner.md": "x\n" });
  sync(root, { home });
  // change two outputs, and make the second one fail to write
  writeFileSync(join(root, ".otterpack/team.yaml"), read(root, ".otterpack/team.yaml").replace("label: PO", "label: Owner"));
  rmSync(join(root, ".vscode"), { recursive: true });
  writeFileSync(join(root, ".vscode"), "not a folder\n");
  const kitAgent = join(root, ".otterpack/local/kits/core/agents/planner.md");
  mkdirSync(join(root, ".otterpack/local/kits/core/agents"), { recursive: true });
  writeFileSync(kitAgent, "local planner\n");
  assert.throws(() => sync(root, { home }));
  rmSync(join(root, ".vscode"));
  const r = sync(root, { home });
  assert.ok(r.written.includes(".vscode/tasks.json"));
  assert.equal(read(root, ".claude/agents/planner.md"), "local planner\n");
  assert.ok(!JSON.parse(read(root, ".otterpack/lock.json")).pending);
});

test("follows symlinks inside a kit", () => {
  const { root, home } = setup(["core", "links"]);
  const kit = join(root, ".otterpack/local/kits/links");
  writeFiles(kit, { "real/agent.md": "a\n", "realskill/SKILL.md": "s\n", "shared/ref.md": "r\n" });
  mkdirSync(join(kit, "agents"));
  mkdirSync(join(kit, "skills"));
  symlinkSync("../real/agent.md", join(kit, "agents/linked.md"));
  symlinkSync("../realskill", join(kit, "skills/linked-skill"));
  symlinkSync("../shared/ref.md", join(kit, "realskill/ref.md"));
  sync(root, { home });
  assert.equal(read(root, ".claude/agents/linked.md"), "a\n");
  assert.equal(read(root, ".agents/skills/linked-skill/SKILL.md"), "s\n");
  assert.equal(read(root, ".claude/skills/linked-skill/ref.md"), "r\n");
});

test("never writes through a symlinked folder (e.g. .claude/skills/x -> ../../.agents/skills/x)", () => {
  const { root, home } = setup(["core"]);
  mkdirSync(join(root, ".agents/skills/handoff"), { recursive: true });
  mkdirSync(join(root, ".claude/skills"), { recursive: true });
  symlinkSync("../../.agents/skills/handoff", join(root, ".claude/skills/handoff"));
  assert.throws(() => sync(root, { home }), /\.claude\/skills\/handoff\/SKILL\.md: goes through the symlink \.claude\/skills\/handoff/);
  assert.ok(!exists(root, ".agents/skills/handoff/SKILL.md"));
});


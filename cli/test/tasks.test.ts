import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseTeam } from "../src/config.ts";
import { renderTasks } from "../src/tasks.ts";

const fixture = (f: string) => fileURLToPath(new URL(`./fixtures/team/${f}`, import.meta.url));

/** VS Code reads tasks.json as JSON with comments; the generated header is // lines. */
function parseJsonc(text: string): any {
  return JSON.parse(text.split("\n").filter((l) => !l.startsWith("//")).join("\n"));
}

test("golden file: labels, icons, colors, order, presentation, runOptions and the open-all task", () => {
  const team = parseTeam(readFileSync(fixture("team.yaml"), "utf8"), "/workspace");
  const ours = renderTasks(team);
  assert.equal(parseJsonc(ours).tasks.length, 14);
  assert.equal(ours, readFileSync(fixture("tasks.json"), "utf8"));
});

test("each seat task runs `otterpack up <id>`", () => {
  const team = parseTeam(readFileSync(fixture("team.yaml"), "utf8"), "/workspace");
  const ours = parseJsonc(renderTasks(team));
  assert.equal(ours.tasks[0].command, "otterpack");
  assert.deepEqual(ours.tasks[0].args, ["up", "claude-po"]);
  assert.equal(ours.tasks.at(-1).command, undefined);
});

test("output starts with a generated-file header and ends with a newline", () => {
  const team = parseTeam(readFileSync(fixture("team.yaml"), "utf8"), "/workspace");
  const text = renderTasks(team);
  assert.match(text, /^\/\/ .*generated by otterpack sync/);
  assert.ok(text.endsWith("}\n"));
});

test("a disabled seat gets no task, and is left out of open all seats", () => {
  const team = parseTeam(readFileSync(fixture("team.yaml"), "utf8"), "/workspace");
  team.seats[1].disabled = true;
  const label = team.seats[1].label;
  const ours = parseJsonc(renderTasks(team));
  assert.equal(ours.tasks.length, 13);
  assert.ok(!ours.tasks.some((t: any) => t.label === label));
  assert.ok(!ours.tasks.at(-1).dependsOn.includes(label));
});
